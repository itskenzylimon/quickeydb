import 'dart:convert';
import '../types/schema.dart';

/// Source generation only: never executes SQL or opens a database.
///
/// Accepts one or more ordinary CREATE TABLE statements supported by [Schema].
/// Rejects data changes, indexes, triggers, views and composite keys. Register
/// the generated DAO instances with QuickeyDB.initialize after reviewing them.
class SqlDaoGenerator {
  const SqlDaoGenerator();

  SqlDaoGeneration generate(String sql) {
    final tables = <SqlDaoTable>[];
    final names = <String>{};
    final classes = <String>{};
    for (final statement in _statements(sql)) {
      if (!RegExp(r'^CREATE\s+TABLE\s+', caseSensitive: false)
              .hasMatch(statement) ||
          !statement.trimRight().endsWith(')')) {
        throw const FormatException(
            'Use ordinary CREATE TABLE statements only. Apply indexes, triggers, data changes and table options separately.');
      }
      final schema = Schema(statement);
      final name = schema.table!;
      if (!RegExp(r'^[A-Za-z][A-Za-z0-9_]*$').hasMatch(name) ||
          name.toLowerCase().startsWith('sqlite_') ||
          name.toLowerCase().startsWith('__quickey')) {
        throw FormatException('Unsupported or reserved table name: $name');
      }
      if (schema.primaryKey == null) {
        throw FormatException(
            'Table $name needs a single primary key for DAO CRUD.');
      }
      final className =
          '${name.split('_').where((s) => s.isNotEmpty).map((s) => s[0].toUpperCase() + s.substring(1)).join()}Dao';
      if (!names.add(name.toLowerCase()) ||
          !classes.add(className.toLowerCase())) {
        throw FormatException('Duplicate table or generated DAO name: $name');
      }
      tables.add(SqlDaoTable._(name, className, statement, schema));
    }
    if (tables.isEmpty) {
      throw const FormatException('Enter at least one CREATE TABLE statement.');
    }
    return SqlDaoGeneration._(List.unmodifiable(tables));
  }

  // A small lexical splitter, not a general SQL grammar. Strings, quoted
  // identifiers and comments cannot inject extra generated Dart statements.
  List<String> _statements(String sql) {
    final statements = <String>[];
    var buffer = StringBuffer();
    String? quote;
    var lineComment = false, blockComment = false, depth = 0;
    for (var i = 0; i < sql.length; i++) {
      final c = sql[i];
      final next = i + 1 < sql.length ? sql[i + 1] : '';
      if (lineComment) {
        if (c == '\n') {
          lineComment = false;
          buffer.write(' ');
        }
        continue;
      }
      if (blockComment) {
        if (c == '*' && next == '/') {
          blockComment = false;
          buffer.write(' ');
          i++;
        }
        continue;
      }
      if (quote != null) {
        buffer.write(c);
        if (c == quote) {
          if (next == quote && quote != ']') {
            buffer.write(next);
            i++;
          } else {
            quote = null;
          }
        }
        continue;
      }
      if (c == '-' && next == '-') {
        lineComment = true;
        i++;
        continue;
      }
      if (c == '/' && next == '*') {
        blockComment = true;
        i++;
        continue;
      }
      if (c == "'" || c == '"' || c == '`' || c == '[') {
        quote = c == '[' ? ']' : c;
      } else if (c == '(') {
        depth++;
      } else if (c == ')') {
        depth--;
        if (depth < 0) throw const FormatException('Unbalanced parentheses.');
      } else if (c == ';') {
        if (depth != 0) {
          throw const FormatException(
              'Unexpected semicolon inside table definition.');
        }
        if (buffer.toString().trim().isNotEmpty) {
          statements.add(buffer.toString().trim());
        }
        buffer = StringBuffer();
        continue;
      }
      buffer.write(c);
    }
    if (quote != null || blockComment || depth != 0) {
      throw const FormatException(
          'Unterminated quote, comment or table definition.');
    }
    if (buffer.toString().trim().isNotEmpty) {
      statements.add(buffer.toString().trim());
    }
    return statements;
  }
}

class SqlDaoTable {
  const SqlDaoTable._(this.tableName, this.className, this.sql, this.schema);
  final String tableName, className, sql;
  final Schema schema;
}

class SqlDaoGeneration {
  const SqlDaoGeneration._(this.tables);
  final List<SqlDaoTable> tables;

  /// Compilable map-based DAOs; no build_runner, model files or part directives.
  /// Foreign keys remain in SQL; configure eager-loading relations separately.
  String get source {
    final output = StringBuffer(
        "// Generated by QuickeyDB. Review before use.\nimport 'package:quickeydb/quickeydb.dart';\n\n");
    for (final table in tables) {
      final literal = jsonEncode(table.sql).replaceAll(r'$', r'\$');
      output.writeln(
          'class ${table.className} extends DataAccessObject<Map<String?, dynamic>> {');
      output.writeln('  ${table.className}() : super(');
      output.writeln('    $literal,');
      output.writeln('    converter: Converter<Map<String?, dynamic>?>(');
      output.writeln('      encode: (row) => Map<String?, dynamic>.from(row),');
      output
          .writeln('      decode: (row) => Map<String?, dynamic>.from(row!),');
      output.writeln(
          '      decodeTable: (row) => Map<String?, dynamic>.from(row!),');
      output.writeln('    ),\n  );\n}\n');
    }
    return output.toString();
  }

  /// Paste these expressions into initialize(dataAccessObjects: ...).
  String get registration =>
      '[${tables.map((t) => '${t.className}()').join(', ')}]';
}
